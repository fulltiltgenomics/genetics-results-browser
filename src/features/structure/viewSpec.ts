/**
 * The view-spec a chat artifact carries to say what the structure viewer shows. The contract
 * is genetics-results-munge's docs/protein-structure.md ("View-spec for the browser viewer")
 * and scripts/protein_structure_contract.py; the two ends cannot import one module, so the
 * constants below are that file's by hand.
 *
 * Nothing here imports Mol*: a spec is parsed before the viewer chunk is fetched, so an
 * artifact that cannot be drawn costs the reader no download.
 */

// the newest shape this build draws. A spec persists in chat history, so a version is never
// dropped from PARSERS once issued
export const VIEW_SPEC_VERSION = 1;
export const VIEW_ROLES = ["case", "control", "both", "neutral"] as const;
export const VIEW_COLOUR_MODES = ["plddt", "uniform"] as const;
export const VIEW_DEFAULT_COLOUR_MODE: ViewColourMode = "plddt";

// the contract's label for the AF3 models; AlphaFold DB models have no label string there
export const AF3_SOURCE_LABEL = "AF3 (AlphaFold Server, generated by the Finucane lab)";

export const STRUCTURE_VIEW_SUFFIX = ".structure-view.json";

// the id is interpolated into the request path, so nothing outside the contract's charset
// may reach it
export const MODEL_FILE_ID_RE = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;

// a spec is written by a script the model wrote, so its sizes are bounded before anything is
// decoded, parsed or drawn. None of these is in the contract; they are the viewer's own limits
export const MAX_SPEC_BYTES = 1_000_000;
export const MAX_TEXT_LENGTH = 80;
export const MAX_POSITION = 100_000;
export const MAX_SPHERE_RADIUS = 100;
export const MAX_RESIDUES = 2000;
export const MAX_LABELS = 40;
const HEX_COLOUR_RE = /^#[0-9a-fA-F]{6}$/;

export type ViewRole = (typeof VIEW_ROLES)[number];
export type ViewColourMode = (typeof VIEW_COLOUR_MODES)[number];

// the viewer owns the palette for roles; the neighbourhood sphere takes the fourth colour
export const ROLE_COLOURS: Record<ViewRole, string> = {
  case: "#d62728",
  control: "#1f77b4",
  both: "#9467bd",
  neutral: "#7f7f7f",
};
export const NEIGHBOURHOOD_COLOUR = "#ff7f0e";

export interface ViewResidue {
  /** residue number as written in the model file */
  filePosition: number;
  label?: string;
  role?: ViewRole;
  /** #rrggbb, always resolved: an explicit colour, else the role's, else neutral */
  colour: string;
  /** false for a label past MAX_LABELS: still told on hover, not drawn in the scene */
  drawLabel: boolean;
}

export interface ViewSpec {
  version: number;
  modelFileId: string;
  accession?: string;
  gene?: string;
  residues: ViewResidue[];
  sphere?: { centre: number; radius: number };
  colourMode: ViewColourMode;
  /** what the caps left out, for the viewer to say so */
  omitted: { residues: number; labels: number };
}

export type ViewSpecResult =
  | { ok: true; spec: ViewSpec }
  | { ok: false; reason: "invalid" | "unsupported-version"; message: string };

class SpecError extends Error {}

const isRecord = (v: unknown): v is Record<string, unknown> =>
  typeof v === "object" && v !== null && !Array.isArray(v);

const position = (v: unknown, what: string): number => {
  if (typeof v !== "number" || !Number.isInteger(v) || v < 1) {
    throw new SpecError(`${what} must be a positive whole number`);
  }
  if (v > MAX_POSITION) throw new SpecError(`${what} is above ${MAX_POSITION}`);
  return v;
};

const optionalString = (v: unknown, what: string): string | undefined => {
  if (v === undefined || v === null) return undefined;
  if (typeof v !== "string") throw new SpecError(`${what} must be text`);
  return v.length > MAX_TEXT_LENGTH ? `${v.slice(0, MAX_TEXT_LENGTH - 1)}…` : v;
};

type ParsedResidue = Omit<ViewResidue, "drawLabel">;

// one entry per position: the first entry's colour stands, and the first label any entry gives
const mergeAndCap = (parsed: ParsedResidue[]): Pick<ViewSpec, "residues" | "omitted"> => {
  const byPosition = new Map<number, ParsedResidue>();
  for (const r of parsed) {
    const first = byPosition.get(r.filePosition);
    if (!first) byPosition.set(r.filePosition, { ...r });
    else if (!first.label?.trim() && r.label?.trim()) first.label = r.label;
  }
  const distinct = [...byPosition.values()];
  const kept = distinct.slice(0, MAX_RESIDUES);
  let labels = 0;
  const residues = kept.map((r) => ({
    ...r,
    drawLabel: !!r.label?.trim() && ++labels <= MAX_LABELS,
  }));
  return {
    residues,
    omitted: {
      residues: distinct.length - kept.length,
      labels: Math.max(0, labels - MAX_LABELS),
    },
  };
};

const parseResidue = (raw: unknown, i: number): ParsedResidue => {
  const what = `residues[${i}]`;
  if (!isRecord(raw)) throw new SpecError(`${what} must be an object`);
  const filePosition = position(raw.file_position, `${what}.file_position`);
  const label = optionalString(raw.label, `${what}.label`);
  const { role, colour } = raw;
  if (role != null && colour != null) {
    throw new SpecError(`${what} carries both role and colour`);
  }
  if (role != null) {
    if (!VIEW_ROLES.includes(role as ViewRole)) {
      throw new SpecError(`${what}.role must be one of ${VIEW_ROLES.join(", ")}`);
    }
    return { filePosition, label, role: role as ViewRole, colour: ROLE_COLOURS[role as ViewRole] };
  }
  if (colour != null) {
    if (typeof colour !== "string" || !HEX_COLOUR_RE.test(colour)) {
      throw new SpecError(`${what}.colour must be a #rrggbb colour`);
    }
    return { filePosition, label, colour: colour.toLowerCase() };
  }
  return { filePosition, label, colour: ROLE_COLOURS.neutral };
};

const parseV1 = (raw: Record<string, unknown>): ViewSpec => {
  const modelFileId = raw.model_file_id;
  if (typeof modelFileId !== "string" || !MODEL_FILE_ID_RE.test(modelFileId)) {
    throw new SpecError("model_file_id is missing or not a model file id");
  }

  let parsed: ParsedResidue[] = [];
  if (raw.residues != null) {
    if (!Array.isArray(raw.residues)) throw new SpecError("residues must be a list");
    parsed = raw.residues.map(parseResidue);
  }

  let sphere: ViewSpec["sphere"];
  if (raw.sphere != null) {
    if (!isRecord(raw.sphere)) throw new SpecError("sphere must be an object");
    const { radius } = raw.sphere;
    if (typeof radius !== "number" || !Number.isFinite(radius) || radius <= 0) {
      throw new SpecError("sphere.radius must be a positive number");
    }
    if (radius > MAX_SPHERE_RADIUS) {
      throw new SpecError(`sphere.radius is above ${MAX_SPHERE_RADIUS} Å`);
    }
    sphere = { centre: position(raw.sphere.centre, "sphere.centre"), radius };
  }

  const colourMode = raw.colour_mode ?? VIEW_DEFAULT_COLOUR_MODE;
  if (!VIEW_COLOUR_MODES.includes(colourMode as ViewColourMode)) {
    throw new SpecError(`colour_mode must be one of ${VIEW_COLOUR_MODES.join(", ")}`);
  }

  return {
    version: 1,
    modelFileId,
    accession: optionalString(raw.accession, "accession"),
    gene: optionalString(raw.gene, "gene"),
    ...mergeAndCap(parsed),
    sphere,
    colourMode: colourMode as ViewColourMode,
  };
};

// one parser per version ever issued. A new version adds an entry and bumps
// VIEW_SPEC_VERSION; an existing entry is never removed or changed in meaning
const PARSERS: Record<number, (raw: Record<string, unknown>) => ViewSpec> = {
  1: parseV1,
};

/** Validate an already-decoded JSON value. Never throws. */
export const parseViewSpec = (raw: unknown): ViewSpecResult => {
  if (!isRecord(raw)) {
    return { ok: false, reason: "invalid", message: "the view is not a JSON object" };
  }
  const { version } = raw;
  if (typeof version !== "number" || !Number.isInteger(version) || version < 1) {
    return { ok: false, reason: "invalid", message: "version is missing or not a whole number" };
  }
  if (version > VIEW_SPEC_VERSION) {
    return {
      ok: false,
      reason: "unsupported-version",
      message: `This structure view was written in a newer format (version ${version}) than this page understands (version ${VIEW_SPEC_VERSION}). Reload the page to get the latest viewer.`,
    };
  }
  const parser = PARSERS[version];
  if (!parser) {
    return { ok: false, reason: "invalid", message: `version ${version} is not a known format` };
  }
  try {
    return { ok: true, spec: parser(raw) };
  } catch (e) {
    if (e instanceof SpecError) return { ok: false, reason: "invalid", message: e.message };
    throw e;
  }
};

/** Parse the text of a `.structure-view.json` artifact. Never throws. */
export const parseViewSpecText = (text: string): ViewSpecResult => {
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch {
    return { ok: false, reason: "invalid", message: "the view is not valid JSON" };
  }
  return parseViewSpec(raw);
};

/**
 * Where a model came from and on what terms, from its id alone: the release names AlphaFold DB
 * files `AF-…` and the lab's AlphaFold Server files `AF3-…`.
 */
export type ModelSource = "alphafold-db" | "alphafold-server" | "unknown";
export const modelSource = (modelFileId: string): ModelSource =>
  modelFileId.startsWith("AF3-")
    ? "alphafold-server"
    : modelFileId.startsWith("AF-")
      ? "alphafold-db"
      : "unknown";

export const isStructureViewName = (name: string): boolean =>
  name.toLowerCase().endsWith(STRUCTURE_VIEW_SUFFIX);
